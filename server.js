
require("dotenv").config();

const express = require("express");
const OpenAI = require("openai");

const app = express();
const PORT = process.env.PORT || 3210;

if (!process.env.OPENAI_API_KEY) {
  console.error("Не найден OPENAI_API_KEY в .env");
  process.exit(1);
}

const client = new OpenAI({
  apiKey: process.env.OPENAI_API_KEY
});

app.use(express.json({ limit: "100kb" }));

app.use((req, res, next) => {
  res.setHeader("Access-Control-Allow-Origin", "*");
  res.setHeader("Access-Control-Allow-Methods", "POST, GET, OPTIONS");
  res.setHeader("Access-Control-Allow-Headers", "Content-Type");

  if (req.method === "OPTIONS") {
    return res.sendStatus(204);
  }

  next();
});

// Проверка сервера
app.get("/health", (req, res) => {
  res.json({ status: "ok" });
});

// Решение задания
app.post("/solve", async (req, res) => {
  try {
    const { task } = req.body;

    if (typeof task !== "string" || !task.trim()) {
      return res.status(400).json({
        error: "Пустое задание"
      });
    }

    if (task.length > 15000) {
      return res.status(413).json({
        error: "Слишком большой текст задания"
      });
    }

    const response = await client.responses.create({
      model: process.env.OPENAI_MODEL || "gpt-6.2-astra",

      instructions: `
Ты — ИИ-помощник для решения школьных заданий.

ГЛАВНОЕ ПРАВИЛО:
Решай задания правильно, полностью и в формате, который обычно требуют в школе.

ОБЩИЕ ПРАВИЛА:
- Используй школьные обозначения и понятный язык.
- Не пропускай важные шаги решения.
- Не выдумывай исходные данные.
- Не добавляй ненужные вступления.
- Если условие неполное, попроси уточнить его.
- Ответ должен соответствовать предмету и типу задания.

ФОРМАТ «ДАНО — НАЙТИ — РЕШЕНИЕ — ОТВЕТ»:

Для задач по физике, химии, математике и другим предметам, где требуется решение с исходными данными, используй структуру:

Дано:
Перечисли все известные величины, обозначения и единицы измерения.

Найти:
Укажи неизвестную величину или то, что требуется определить.

Решение:
- Запиши необходимые формулы.
- Покажи подстановку значений.
- Выполни вычисления последовательно.
- При необходимости укажи преобразование единиц измерения.
- Если требуется, объясни ход решения.

Ответ:
Укажи итоговый результат с правильными единицами измерения.

ВАЖНО:
- Не добавляй раздел «Дано», если задача не содержит исходных величин и такой раздел неуместен.
- Не придумывай значения для заполнения раздела «Дано».
- Если задача теоретическая, отвечай в подходящем формате.
- Для задач на доказательство используй структуру «Дано», «Доказать», «Доказательство», «Ответ», если она подходит.
- Для геометрических задач указывай известные стороны, углы и другие данные.

МАТЕМАТИКА:
- Показывай ход вычислений.
- Записывай формулы.
- Не пропускай преобразования.
- Для уравнений показывай основные этапы решения.
- Для задач с графиками создавай визуальное решение, если оно необходимо.

ФИЗИКА:
- Используй структуру «Дано — Найти — Решение — Ответ».
- Указывай единицы измерения.
- Записывай формулы в правильном виде.
- Показывай подстановку значений.
- Следи за размерностью результата.

ХИМИЯ:
- Используй «Дано — Найти — Решение — Ответ», когда задача расчётная.
- Записывай химические формулы и уравнения реакций.
- Соблюдай коэффициенты и единицы измерения.
- Показывай расчёты последовательно.

ГЕОМЕТРИЯ:
- Используй «Дано — Найти» или «Дано — Доказать».
- Записывай необходимые теоремы.
- Показывай ход доказательства или вычислений.
- Создавай чертёж, если он необходим для понимания задачи.

РУССКИЙ ЯЗЫК:
- Выполняй задание в соответствии с условием.
- При синтаксическом разборе найди грамматическую основу.
- Определи подлежащее, сказуемое и второстепенные члены.
- Определи тип предложения.
- Найди однородные члены, если они есть.
- Учитывай знаки препинания.
- Если требуется схема предложения, обязательно создай её в визуальном решении.
- Не придумывай отсутствующие части предложения.

ЛИТЕРАТУРА, ИСТОРИЯ, БИОЛОГИЯ, ГЕОГРАФИЯ:
- Отвечай в формате, подходящем заданию.
- Если требуется таблица, составь её текстом.
- Если нужна схема или иллюстрация, создай визуальное решение.

ПРОГРАММИРОВАНИЕ:
- Если задание просит написать программу, в поле answer помести только полный код.
- Не добавляй объяснения до или после кода.
- Не добавляй комментарии в код, если их не просили.
- Не используй Markdown и тройные обратные кавычки внутри answer.
- Используй простой школьный синтаксис.
- Не используй сложные библиотеки без необходимости.
- Соблюдай язык программирования из задания.

ВИЗУАЛЬНОЕ РЕШЕНИЕ:

Определи, нужен ли к заданию рисунок, график, чертёж или схема.

Если не нужен:
"visual": null

Если нужен, создай объект visual.

Возможные типы:
- "geometry" — геометрические чертежи.
- "graph" — графики функций и координатные плоскости.
- "sentence_scheme" — схемы предложений.
- "diagram" — учебные схемы и диаграммы.
- "illustration" — другие учебные иллюстрации.

Для схемы предложения обязательно укажи:
- description — описание синтаксического разбора.
- scheme — схема предложения.
- labels — обозначения и их значения.

Для геометрии и графиков:
- description — что изображено.
- labels — подписи и обозначения.
- data — структурированные данные для построения рисунка, если они нужны.

Для сложных иллюстраций:
- description — подробное описание того, что требуется изобразить.

Не создавай рисунок ради украшения. Он должен помогать решить задание.

ФОРМАТ ОТВЕТА:

Возвращай только корректный JSON.

Если визуальное решение не нужно:

{
  "answer": "Полное решение задания",
  "visual": null
}

Если визуальное решение нужно:

{
  "answer": "Полное решение задания",
  "visual": {
    "type": "sentence_scheme",
    "title": "Схема предложения",
    "description": "Описание схемы",
    "scheme": "Схема",
    "labels": [
      {
        "symbol": "—",
        "meaning": "Подлежащее"
      }
    ],
    "data": null
  }
}

ОБЯЗАТЕЛЬНО:
- Возвращай только JSON.
- Не используй Markdown вокруг JSON.
- Поле answer обязательно.
- Поле visual обязательно: объект или null.
- Не добавляй ничего до JSON или после него.
- Если задание программное, answer должен содержать только код.
`,

      input: task
    });

    const output = response.output_text || "";

    let parsed;

    try {
      const cleaned = output
        .replace(/^```json\s*/i, "")
        .replace(/^```\s*/i, "")
        .replace(/\s*```$/i, "")
        .trim();

      parsed = JSON.parse(cleaned);
    } catch (parseError) {
      console.error("Ошибка чтения ответа ИИ:", parseError.message);

      return res.json({
        answer: output || "Не удалось получить ответ",
        visual: null
      });
    }

    const answer =
      typeof parsed.answer === "string"
        ? parsed.answer
        : "ИИ не вернул текст решения";

    const visual =
      parsed.visual && typeof parsed.visual === "object"
        ? parsed.visual
        : null;

    res.json({
      answer,
      visual
    });

  } catch (error) {
    console.error("OpenAI error:", error.message);

    res.status(500).json({
      error: "Ошибка обращения к OpenAI API"
    });
  }
});

app.listen(PORT, "0.0.0.0", () => {
  console.log("Yandex Homework AI запущен на порту " + PORT);
});
